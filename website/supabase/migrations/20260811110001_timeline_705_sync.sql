UPDATE public.timeline_events
SET description = '7년이 넘는 시간이 흘렀지만 풍천리 주민들의 투쟁은 계속되고 있습니다. 정기 집회는 705여 차를 넘어섰고, 전국 140여 개 단체가 연대에 합류하며 풍천리의 싸움은 지역을 넘어 전국적인 환경·주민권 이슈로 확산되고 있습니다.',
    updated_at = now()
WHERE title = '투쟁 계속, 전국 140여 개 단체 연대'
  AND description NOT LIKE '%705%';
